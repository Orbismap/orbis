// Builds src/pro/tiles3d/geoid.generated.ts: a coarse EGM96 geoid grid (2 degrees, decimetres) so streamed 3D tiles (ellipsoid
// heights) can be lowered onto the map's sea level anywhere. Source: GeographicLib's egm96-15.pgm
// (https://sourceforge.net/projects/geographiclib/files/geoids-distrib/egm96-15.zip). Usage: node scripts/build-geoid.mjs path/to/egm96-15.pgm
import { readFileSync, writeFileSync } from 'node:fs';

const file = process.argv[2];
if (!file) { console.error('usage: node scripts/build-geoid.mjs egm96-15.pgm'); process.exit(1); }
const buf = readFileSync(file);
// header: P5 + comment lines + "1440 721" + "65535", then big-endian uint16
let pos = 0;
const line = () => { const s = pos; while (buf[pos] !== 0x0a) pos++; return buf.toString('latin1', s, pos++); };
const meta = {};
let w = 0, h = 0;
for (;;) {
  const l = line();
  if (l.startsWith('#')) { const m = l.match(/^# (Offset|Scale)\s+(\S+)/); if (m) meta[m[1]] = Number(m[2]); continue; }
  if (l === 'P5') continue;
  if (!w) { [w, h] = l.split(/\s+/).map(Number); continue; }
  break; // maxval line
}
const at = (r, c) => meta.Offset + meta.Scale * buf.readUInt16BE(pos + 2 * (r * w + c));
const STEP = 2, per = w / 360; // pixels per degree
const rows = 180 / STEP + 1, cols = 360 / STEP;
const out = new Int16Array(rows * cols);
for (let r = 0; r < rows; r++) for (let c = 0; c < cols; c++) out[r * cols + c] = Math.round(at(Math.round(r * STEP * per), Math.round(c * STEP * per) % w) * 10);
const b64 = Buffer.from(out.buffer).toString('base64');
writeFileSync(new URL('../src/pro/tiles3d/geoid.generated.ts', import.meta.url), `// Generated by scripts/build-geoid.mjs from EGM96 (GeographicLib egm96-15.pgm). Do not edit.
// ${rows} rows (90N to 90S) x ${cols} columns (0E eastwards), every ${STEP} degrees, decimetres, little-endian int16, base64.
export const GEOID_STEP = ${STEP};
export const GEOID_ROWS = ${rows};
export const GEOID_COLS = ${cols};
export const GEOID_DM_B64 = '${b64}';
`);
console.log('geoid grid', rows, 'x', cols, 'bytes', b64.length);
